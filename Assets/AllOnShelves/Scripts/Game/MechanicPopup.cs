        }

        /// <param name="sprite">своя картинка вместо стандартной (у «Лишнего товара» — тот товар, что в уровне)</param>
        public void Setup(string mechanic, Action onOk, string sprite = null)
        {
            var info = Info(mechanic);
            title.text = mechanic == "rules" ? info.title : "Новое: " + info.title;
            text.text = info.text;
            picture.sprite = ArtLibrary.S(string.IsNullOrEmpty(sprite) ? info.sprite : sprite) ?? ArtLibrary.S(info.sprite);
            picture.preserveAspect = true;
            ArtLibrary.Fit(picture, 220f);   // у каждой картинки свои пропорции
            okButton.onClick.RemoveAllListeners();
            okButton.onClick.AddListener(() => Hide(onOk));
            Show();
            AudioService.Play("jingle_new_mechanic");
        }
    }
}
