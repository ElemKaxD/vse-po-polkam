using System;
using TMPro;
using UnityEngine;
using UnityEngine.UI;

namespace AllOnShelves.Game
{
    /// <summary>
    /// Карточка «Новое!» перед уровнем с новой механикой (ГДД 7.3). Про каждую новинку
    /// рассказывает енот — подробно, что это и как с этим играть (просьба 26.09.2026).
    /// </summary>
    public class MechanicPopup : Popup
    {
        public Image picture;
        public TextMeshProUGUI title;
        public TextMeshProUGUI text;
        public Button okButton;
        public RectTransform raccoon;

        public static (string title, string text, string sprite) Info(string mechanic)
        {
            switch (mechanic)
            {
                case "lock": return ("Закрытая секция",
                    "На этой полке висит замок с числом. Каждый раскупленный набор снимает с него единицу: " +
                    "дошло до нуля — полка открылась и ею можно пользоваться. Пока замок висит, считай, " +
                    "что полки нет, и держи место в тележке про запас.", "obj_lock_closed");
                case "box": return ("Коробка «?»",
                    "В коробке товар, но какой — заранее не видно. Она раскрывается, когда доезжает до края " +
                    "ленты. Не занимай последнюю свободную полку перед коробкой: вдруг оттуда приедет новый вид.",
                    "obj_box_closed");
                case "extra": return ("Лишний товар",
                    "Этого товара нет в заказе — на полку его не поставить. Нажми на него, и он уедет в тележку: " +
                    "за ним придёт покупатель, заберёт и оставит чаевые. Держи для него место в тележке!", "item_cucumber");
                case "customer": return ("Покупатель",
                    "Покупатель приходит за товаром и ждёт несколько ходов — сколько именно, показывают сердечки. " +
                    "Нужный товар он заберёт прямо из тележки и заплатит чаевые. Уйдёт ни с чем — чаевых не будет.",
                    "chr_customer_bunny_wait");
                case "perish": return ("Скоропорт",
                    "У товара с часиками свой срок: пока он лежит в тележке, часы тикают. Досчитают до нуля — " +
                    "товар испортится, и набор с ним уже не собрать. Такие товары раскладывай в первую очередь.",
                    "icon_clock");
                case "freezer": return ("Морозилка",
                    "Замороженные товары кладут только в морозильную секцию — на обычную полку они не встанут. " +
                    "В тележке заморозка тает, поэтому не вози её кругами: увидел — сразу в морозилку.",
                    "brd_freezer_closed");
                case "big": return ("Крупный товар",
                    "Арбуз большой: в тележке он занимает два места сразу, а на полку таких влезает только два " +
                    "вместо трёх. Планируй место заранее — с арбузом в тележке манёвра почти нет.", "item_watermelon");
                case "pallet": return ("Паллета",
                    "На паллете приехали сразу три одинаковых товара, и уедут они тоже вместе — в одну секцию. " +
                    "Значит, к её приезду нужна полка, где свободно три места, иначе паллету не разгрузить.",
