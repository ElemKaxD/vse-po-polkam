                case "belt2": return ("Две ленты",
                    "Теперь лент две, и двигаются они по отдельности: берёшь товар с одной — вторая стоит. " +
                    "Это свобода выбора, но и вдвое больше видов товара сразу. Смотри на обе, прежде чем ходить.",
                    "brd_belt_roller");
                case "door": return ("Дверца морозилки",
